import hashlib
import io
import json
import os
from pathlib import Path
import tempfile
import tarfile
import unittest
from unittest.mock import patch

import android_pub_inputs as pub


class PubInputsTest(unittest.TestCase):
    def setUp(self):
        temp = tempfile.TemporaryDirectory()
        self.addCleanup(temp.cleanup)
        self.root = Path(temp.name)
        self.config = self.root / 'package_config.json'
        self.lock = self.root / 'pubspec.lock'
        self.code = self.root / 'accepted'
        self.code.mkdir()

    def native_lock(self, sha='a' * 64, url='https://pub.dev'):
        return f'''packages:
  _tool_meta:
    dependency: "direct main"
    description:
      name: _tool_meta
      sha256: "{sha}"
      url: "{url}"
    source: hosted
    version: "1.2.3"
sdks:
  dart: ">=3.10.0 <4.0.0"
'''

    def write_config(self, **entry_changes):
        entry = {'name': '_tool_meta', 'rootUri': self.code.as_uri() + '/',
                 'packageUri': 'lib/', 'languageVersion': '3.10'}
        entry.update(entry_changes)
        value = {'configVersion': 2, 'packages': [entry],
                 'generator': 'pub', 'generatorVersion': '3.13.3'}
        self.config.write_text(json.dumps(value))
        return value

    def verify(self):
        return pub.verify_package_config(self.config, {'_tool_meta': self.code},
                                         {'_tool_meta': '3.10'})

    def test_generated_plugin_map_cannot_select_an_extra_or_external_package(self):
        path = self.root / 'plugins.json'
        entry = {'name': '_tool_meta', 'path': str(self.code) + '/', 'dependencies': []}
        document = {'info': 'Generated by accepted Flutter',
                    'plugins': {name: [] for name in ('android', 'ios', 'linux', 'macos', 'web', 'windows')},
                    'dependencyGraph': [{'name': '_tool_meta', 'dependencies': []}],
                    'date_created': 'same-run', 'version': '3.47.4',
                    'swift_package_manager_enabled': {'ios': False, 'macos': False}}
        document['plugins']['android'] = [entry]
        path.write_text(json.dumps(document))
        self.assertEqual(pub.verify_plugin_map(path, {'_tool_meta': self.code}), 1)
        for change in [{'path': str(self.root / 'unselected')},
                       {'name': 'extra'}, {'dependencies': ['extra']},
                       {'name': []}]:
            original = dict(entry)
            entry.update(change)
            path.write_text(json.dumps(document))
            with self.assertRaises(pub.MaterialError):
                pub.verify_plugin_map(path, {'_tool_meta': self.code})
            entry.clear()
            entry.update(original)

    def test_native_lock_parses_data_without_accepting_its_packages(self):
        self.lock.write_text(self.native_lock())
        data = pub.read_native_lock(self.lock)
        self.assertEqual(data['packages']['_tool_meta']['version'], '1.2.3')
        self.assertNotIn('accepted', data)

    def hosted_fixture(self):
        archive = self.root / 'package.tar.gz'
        files = {'pubspec.yaml': b'name: _tool_meta\nenvironment:\n  sdk: ^3.10.0\n',
                 'lib/tool.dart': b'accepted source bytes; never execute'}
        with tarfile.open(archive, 'w:gz') as output:
            for name, data in files.items():
                entry = tarfile.TarInfo(name)
                entry.mode = 0o644
                entry.size = len(data)
                output.addfile(entry, io.BytesIO(data))
        self.lock.write_text(self.native_lock(hashlib.sha256(archive.read_bytes()).hexdigest()))
        cache = self.root / 'cache'
        package = cache / 'hosted/pub.dev/_tool_meta-1.2.3'
        (package / 'lib').mkdir(parents=True)
        for name, data in files.items():
            (package / name).write_bytes(data)
        return cache, package, {'_tool_meta-1.2.3': archive}

    def test_hosted_content_and_language_come_from_accepted_archive_not_sidecar(self):
        cache, package, archives = self.hosted_fixture()
        roots, languages = pub.verify_hosted_packages(pub.read_native_lock(self.lock), cache, archives)
        self.assertEqual(roots['_tool_meta'], package)
        self.assertEqual(languages['_tool_meta'], '3.10')
        source = package / 'lib/tool.dart'
        before = source.stat()
        source.write_bytes(b'replaced source bytes; never execute')
        os.utime(source, ns=(before.st_atime_ns, before.st_mtime_ns))
        sidecar = cache / 'hosted-hashes/pub.dev'
        sidecar.mkdir(parents=True)
        (sidecar / '_tool_meta-1.2.3.sha256').write_text('a' * 64)
        with self.assertRaises(pub.MaterialError):
            pub.verify_hosted_packages(pub.read_native_lock(self.lock), cache, archives)

    def test_hosted_cache_parent_cannot_redirect_reads_outside_selected_cache(self):
        cache, package, archives = self.hosted_fixture()
        foreign = self.root / 'redirected-cache'
        foreign.mkdir()
        (foreign / 'hosted').symlink_to(cache / 'hosted', target_is_directory=True)
        with self.assertRaises(OSError):
            pub.verify_hosted_packages(pub.read_native_lock(self.lock), foreign, archives)

    def test_language_constraint_is_explicit_and_never_guessed(self):
        for constraint, expected in [('^3.11.0-0', '3.11'),
                                     ("'>=2.18.0 <4.0.0'", '2.18')]:
            self.assertEqual(pub.package_language('environment:\n  sdk: ' + constraint), expected)
        for constraint in ['any', '*alias', '>=3.0.0 || >=2.12.0', '<4.0.0']:
            with self.assertRaises(pub.MaterialError):
                pub.package_language('environment:\n  sdk: ' + constraint)

    def test_missing_hash_or_wrong_receiver_does_not_become_an_identity(self):
        for text in [self.native_lock(sha=''), self.native_lock(url='http://pub.dev'),
                     self.native_lock(url='https://pub.dev.attacker.example'),
                     self.native_lock().replace('      sha256:', '      ignored:')]:
            with self.subTest(text=text):
                self.lock.write_text(text)
                with self.assertRaises(pub.MaterialError):
                    pub.read_native_lock(self.lock)

    def test_yaml_alias_duplicate_and_unsupported_structure_fail(self):
        for text in [self.native_lock().replace('source: hosted', 'source: *alias'),
                     self.native_lock().replace('source: hosted', 'source: hosted\n    source: git'),
                     self.native_lock().replace('  _tool_meta:', '   _tool_meta:'),
                     'packages: {}\nsdks: {}\n']:
            with self.subTest(text=text):
                self.lock.write_text(text)
                with self.assertRaises(pub.MaterialError):
                    pub.read_native_lock(self.lock)

    def test_package_roots_are_exact_but_do_not_authenticate_content(self):
        self.write_config()
        result = self.verify()
        self.assertEqual(result['packages_checked'], 1)
        self.assertFalse(result['source_contents_verified_here'])
        self.assertFalse(result['profile_ready'])

    def test_foreign_root_is_rejected_without_reading_it(self):
        private = self.root / 'private'
        private.write_bytes(b'private contents')
        inode = private.stat().st_ino
        original = os.fdopen

        def no_private(fd, *args, **kwargs):
            self.assertNotEqual(os.fstat(fd).st_ino, inode)
            return original(fd, *args, **kwargs)

        for root in [private.as_uri(), '../private', 'https://pub.dev/code',
                     'file://other-host/code', '%2e%2e/private']:
            with self.subTest(root=root), patch.object(os, 'fdopen', no_private):
                self.write_config(rootUri=root)
                with self.assertRaises(pub.MaterialError):
                    self.verify()

    def test_loading_semantics_are_not_inferred_from_a_matching_name(self):
        for changes in [{'packageUri': '../outside/'}, {'packageUri': 'src/'},
                        {'languageVersion': '3.13'}, {'name': 'unaccepted'}]:
            with self.subTest(changes=changes):
                self.write_config(**changes)
                with self.assertRaises(pub.MaterialError):
                    self.verify()

    def test_empty_extra_and_duplicate_packages_fail(self):
        for mode in ['empty', 'extra', 'duplicate']:
            with self.subTest(mode=mode):
                value = self.write_config()
                if mode == 'empty':
                    value['packages'] = []
                elif mode == 'extra':
                    value['packages'].append(dict(value['packages'][0], name='another'))
                else:
                    value['packages'].append(value['packages'][0])
                self.config.write_text(json.dumps(value))
                with self.assertRaises(pub.MaterialError):
                    self.verify()

    def test_duplicate_json_fields_and_config_root_overrides_fail(self):
        self.config.write_text('{"configVersion":2,"configVersion":2,"packages":[]}')
        with self.assertRaises(pub.MaterialError):
            self.verify()
        value = self.write_config()
        value['pubCache'] = (self.root / 'foreign-cache').as_uri()
        self.config.write_text(json.dumps(value))
        with self.assertRaises(pub.MaterialError):
            self.verify()


if __name__ == '__main__':
    unittest.main()
